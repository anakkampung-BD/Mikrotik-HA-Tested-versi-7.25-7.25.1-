def _package_bytes() -> bytes:
    return base64.b64decode(
        "".join(line.strip().strip('"') for line in PACKAGE_B64.splitlines() if line.strip())
    )


def escape_rsc_source(content: str) -> str:
    content = content.replace("\\", "\\\\")
    content = content.replace("$", "\\$")
    content = content.replace("\n", "\\\n\t\\n")
    content = content.replace('"', '\\"')
    return content


def scripts_sha1(script_paths: list[Path]) -> str:
    h = hashlib.sha1()
    for path in script_paths:
        h.update(path.read_bytes())
    return h.hexdigest()


def build_ha_init(ha_version: str, script_paths: list[Path]) -> str:
    lines: list[str] = [":do {", "/system script"]
    for path in script_paths:
        name = path.stem
        source = escape_rsc_source(path.read_text(encoding="utf-8"))
        lines.append(f"remove [find name={name}_new]")
        if name in NO_PERM_SCRIPTS:
            lines.append(
                f'add name={name}_new owner=admin dont-require-permissions=yes '
                f'policy={POLICY} source="{source}"'
            )
        else:
            lines.append(
                f'add name={name}_new owner=admin '
                f'policy={POLICY} source="{source}"'
            )
    for path in script_paths:
        name = path.stem
        lines.append(f"remove [find name={name}_old]")
        lines.append(f"remove [find name={name}]")
        lines.append(f"set name={name} [find name={name}_new]")
    lines.append("/system script run [find name=ha_functions]")
    lines.append("}")
    return ("\n".join(lines) + "\n").replace("%%%HA_VERSION%%%", ha_version)


def build_heartbeat(version_tag: str, hb_scripts_dir: Path) -> str:
    lines: list[str] = [":do {", "/system script"]
    for filename in HB_SCRIPT_ORDER:
        path = hb_scripts_dir / filename
        if not path.is_file():
            raise FileNotFoundError(f"Script heartbeat hilang: {path}")
        name = path.stem
        source = escape_rsc_source(path.read_text(encoding="utf-8"))
        lines.append(f"remove [find name={name}]")
        lines.append(f"remove [find name={name}_new]")
        lines.append(f'add name={name} owner=admin policy={POLICY} source="{source}"')
    lines.append("/system script run [find name=ha_hb_functions]")
    lines.append(
        f':put "HA heartbeat scripts loaded ({version_tag}). '
        f'Next: \\$HAHeartbeatInstall interfaces=\\"IF1,IF2\\""'
    )
    lines.append("}")
    return "\n".join(lines) + "\n"


def extract_package(root: Path) -> list[str]:
    written: list[str] = []
    with zipfile.ZipFile(io.BytesIO(_package_bytes()), "r") as zf:
        for info in zf.infolist():
            if info.is_dir():
                continue
            rel = info.filename
            if rel in KEEP_TOP or rel in GENERATED:
                continue
            out = root / rel
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(zf.read(info))
            written.append(rel)
    return written


def generate_artifacts(root: Path) -> tuple[str, str]:
    scripts_dir = root / "scripts"
    version_file = root / "VERSION"
    script_paths = sorted(scripts_dir.glob("*.script"))
    if not script_paths:
        raise FileNotFoundError("scripts/*.script kosong — extract gagal?")
    base_ver = version_file.read_text(encoding="utf-8").strip()
    ha_version = f"{base_ver} - {scripts_sha1(script_paths)}"
    (root / "HA_init.rsc").write_text(
        build_ha_init(ha_version, script_paths).replace("\r\n", "\n"),
        encoding="utf-8",
    )
    hb_tag = f"1.0-HB-{date.today().strftime('%Y%m%d')}"
    hb_out = root / "heartbeat" / "HA_heartbeat.rsc"
    hb_out.parent.mkdir(parents=True, exist_ok=True)
    hb_out.write_text(
        build_heartbeat(hb_tag, root / "heartbeat" / "scripts").replace("\r\n", "\n"),
        encoding="utf-8",
    )
    return ha_version, hb_tag


def pack_package(root: Path, self_path: Path) -> int:
    files: dict[str, bytes] = {}
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(root).as_posix()
        if rel in KEEP_TOP or rel in GENERATED:
            continue
        if path.name == ".DS_Store" or path.suffix == ".pyc":
            continue
        if "__pycache__" in path.parts:
            continue
        if path.name.startswith("_HA_generate") or path.name.startswith("_payload"):
            continue
        if path.name.startswith("_build"):
            continue
        files[rel] = path.read_bytes()
    if not files:
        print("ERROR: tidak ada file untuk di-pack", file=sys.stderr)
        return 1

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for rel, data in files.items():
            zf.writestr(rel, data)
    blob = base64.b64encode(buf.getvalue()).decode("ascii")
    chunk_lines = [blob[i : i + 76] for i in range(0, len(blob), 76)]
    blob_literal = "\n".join(f'    "{c}"' for c in chunk_lines)

    text = self_path.read_text(encoding="utf-8")
    start = text.find("PACKAGE_B64 = (")
    if start < 0:
        print("ERROR: PACKAGE_B64 tidak ditemukan", file=sys.stderr)
        return 1
    end = text.find("\n)\n\n\ndef _package_bytes", start)
    if end < 0:
        print("ERROR: penutup PACKAGE_B64 tidak ditemukan", file=sys.stderr)
        return 1
    new_text = text[: start + len("PACKAGE_B64 = (")] + "\n" + blob_literal + text[end:]
    self_path.write_text(new_text, encoding="utf-8")
    print(f"Packed {len(files)} files into {self_path.name} ({len(blob)} base64 chars)")
    for rel in sorted(files):
        print(f"  + {rel}")
    return 0


def check_artifacts(root: Path) -> int:
    ha_path = root / "HA_init.rsc"
    if not ha_path.is_file():
        print("FAIL: HA_init.rsc belum ada", file=sys.stderr)
        return 1
    existing = ha_path.read_text(encoding="utf-8")
    script_paths = sorted((root / "scripts").glob("*.script"))
    base_ver = (root / "VERSION").read_text(encoding="utf-8").strip()
    ha_version = f"{base_ver} - {scripts_sha1(script_paths)}"
    fresh = build_ha_init(ha_version, script_paths)
    if existing == fresh:
        print(f"OK: HA_init.rsc identik. Version: {ha_version}")
        return 0
    print("DIFF: HA_init.rsc berbeda dari hasil generate.", file=sys.stderr)
    return 2


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Ekspansi paket HA + generate HA_init.rsc / HA_heartbeat.rsc"
    )
    parser.add_argument(
        "--pack",
        action="store_true",
        help="Pack ulang payload dari folder lokal ke HA_generate.py (maintainer)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Cek HA_init.rsc vs generate ulang",
    )
    parser.add_argument(
        "--no-extract",
        action="store_true",
        help="Jangan extract payload; hanya generate .rsc dari scripts/ yang ada",
    )
    args = parser.parse_args(argv)

    try:
        if args.pack:
            return pack_package(ROOT, Path(__file__).resolve())

        if args.check:
            if not (ROOT / "scripts").is_dir():
                extract_package(ROOT)
            return check_artifacts(ROOT)

        if not args.no_extract:
            written = extract_package(ROOT)
            print(f"Extracted {len(written)} files from embedded package")

        ha_version, hb_tag = generate_artifacts(ROOT)
        print("Generated HA_init.rsc")
        print(f"  Version: {ha_version}")
        print(f"Generated heartbeat/HA_heartbeat.rsc ({hb_tag})")
        print()
        print("Lanjut:")
        print("  1. Edit scripts/ha_config.script (haBaseIdentity) + placeholder lain")
        print("  2. python3 HA_generate.py --no-extract")
        print("  3. Baca STEP-BY-STEP.md lalu /import HA_init.rsc di router ACTIVE")
        print("  Operasional: OPERATIONS.md")
        return 0
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
